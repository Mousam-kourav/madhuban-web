// Heading-structure analyzer for Step 6 of the audit.
// Reads extracted .md files from audit/02-old-site-content/ and audit/03-new-site-content/
// and produces a hierarchy audit per page.
const fs = require('fs');
const path = require('path');

const OLD_DIR = path.resolve(__dirname, '02-old-site-content');
const NEW_DIR = path.resolve(__dirname, '03-new-site-content');

function parseHeadings(file) {
  const text = fs.readFileSync(file, 'utf8');
  const re = /^ *- \*\*(H[1-6]):\*\* (.+)$/gm;
  const headings = [];
  let m;
  while ((m = re.exec(text)) !== null) {
    headings.push({ level: parseInt(m[1][1]), text: m[2].trim() });
  }
  return headings;
}

function audit(headings) {
  const violations = [];
  const h1Count = headings.filter(h => h.level === 1).length;
  if (h1Count === 0) violations.push('NO_H1');
  if (h1Count > 1) violations.push(`MULTIPLE_H1 (${h1Count})`);

  // Check for skipped levels
  let prev = 0;
  let skipped = false;
  for (const h of headings) {
    if (prev > 0 && h.level > prev + 1) {
      violations.push(`SKIP_LEVEL (jumped H${prev}→H${h.level} at "${h.text.slice(0, 50)}")`);
      skipped = true;
      break;
    }
    prev = h.level;
  }

  // Check for first heading not being H1 (when H1 exists)
  if (h1Count > 0 && headings.length > 0 && headings[0].level !== 1) {
    violations.push(`H1_NOT_FIRST (first heading is H${headings[0].level})`);
  }

  return { h1Count, headings, violations };
}

function readDir(dir) {
  return fs.readdirSync(dir).filter(f => f.endsWith('.md')).map(f => ({
    basename: f.replace(/\.md$/, ''),
    fullPath: path.join(dir, f),
  }));
}

const oldFiles = readDir(OLD_DIR);
const newFiles = readDir(NEW_DIR);

const oldMap = Object.fromEntries(oldFiles.map(f => [f.basename, audit(parseHeadings(f.fullPath))]));
const newMap = Object.fromEntries(newFiles.map(f => [f.basename, audit(parseHeadings(f.fullPath))]));

const lines = [];
const push = s => lines.push(s);

push('# 06 — Heading Structure Audit');
push('');
push('**Date:** 2026-05-18');
push('Source files: `audit/02-old-site-content/*.md` and `audit/03-new-site-content/*.md`.');
push('Per-page heading lists are in those files; this report flags violations and OLD vs NEW comparison.');
push('Generated by `audit/.heading-audit.cjs`.');
push('');

// Section 1 — Summary table
push('## 1. Summary of structural violations');
push('');
push('Definitions:');
push('- **NO_H1** — page has zero `<h1>` elements. Fail.');
push('- **MULTIPLE_H1** — page has more than one `<h1>`. Confuses crawlers about page topic.');
push('- **SKIP_LEVEL** — heading hierarchy jumps a level (e.g. H2 directly to H4). Hurts accessibility and screen-reader navigation.');
push('- **H1_NOT_FIRST** — H1 appears after another heading. Crawlers expect H1 first.');
push('');
push('### NEW build violations');
push('');
push('| Page | H1 count | Violations |');
push('|---|---:|---|');
const newViolations = Object.entries(newMap).filter(([_, r]) => r.violations.length > 0);
newViolations.sort((a, b) => a[0].localeCompare(b[0]));
if (newViolations.length === 0) {
  push('| _(none — all NEW pages clean)_ | | |');
} else {
  newViolations.forEach(([page, r]) => {
    push(`| \`${page}\` | ${r.h1Count} | ${r.violations.join('; ')} |`);
  });
}
push('');
push('### OLD build violations (informational)');
push('');
push('OLD violations are not actionable in this rebuild (the OLD site is being replaced) but are worth knowing — if an OLD page had bad structure, its ranking equity may already be weaker than the impression count suggests.');
push('');
push('| Page | H1 count | Violations |');
push('|---|---:|---|');
const oldViolations = Object.entries(oldMap).filter(([_, r]) => r.violations.length > 0);
oldViolations.sort((a, b) => a[0].localeCompare(b[0]));
if (oldViolations.length === 0) {
  push('| _(none)_ | | |');
} else {
  oldViolations.forEach(([page, r]) => {
    push(`| \`${page}\` | ${r.h1Count} | ${r.violations.join('; ')} |`);
  });
}
push('');

// Section 2 — Per-page comparison with OLD equivalents
push('## 2. NEW vs OLD heading hierarchy comparison');
push('');
push('For each NEW page that has an OLD equivalent (by basename), show both heading hierarchies side by side.');
push('NEW-only pages (no OLD equivalent) are listed in section 3.');
push('');

const haveOld = Object.keys(newMap).filter(k => oldMap[k]).sort();
const newOnly = Object.keys(newMap).filter(k => !oldMap[k]).sort();
const oldOnly = Object.keys(oldMap).filter(k => !newMap[k]).sort();

haveOld.forEach(page => {
  push(`### \`${page}\``);
  push('');
  push('| OLD heading | NEW heading |');
  push('|---|---|');
  const o = oldMap[page].headings;
  const n = newMap[page].headings;
  const max = Math.max(o.length, n.length);
  for (let i = 0; i < max; i++) {
    const oo = o[i] ? `H${o[i].level}: ${o[i].text.slice(0, 80)}` : '_(none)_';
    const nn = n[i] ? `H${n[i].level}: ${n[i].text.slice(0, 80)}` : '_(none)_';
    push(`| ${oo} | ${nn} |`);
  }
  push('');
  // Diff: what's preserved, what's lost
  const oldTexts = new Set(o.map(h => h.text.toLowerCase()));
  const newTexts = new Set(n.map(h => h.text.toLowerCase()));
  const lost = o.filter(h => !newTexts.has(h.text.toLowerCase())).slice(0, 8);
  const added = n.filter(h => !oldTexts.has(h.text.toLowerCase())).slice(0, 8);
  if (lost.length > 0) {
    push(`**Headings on OLD lost on NEW (up to 8 shown):**`);
    lost.forEach(h => push(`- H${h.level}: ${h.text}`));
    push('');
  }
  if (added.length > 0) {
    push(`**Headings new on NEW (up to 8 shown):**`);
    added.forEach(h => push(`- H${h.level}: ${h.text}`));
    push('');
  }
});

push('## 3. NEW-only pages (no OLD equivalent)');
push('');
push('Heading hierarchies for NEW additions. No OLD comparison possible.');
push('');
newOnly.forEach(page => {
  const r = newMap[page];
  push(`### \`${page}\``);
  push(`- H1 count: ${r.h1Count}${r.violations.length > 0 ? ' · Violations: **' + r.violations.join(', ') + '**' : ''}`);
  push('');
  push('Hierarchy:');
  if (r.headings.length === 0) {
    push('_(no headings found)_');
  } else {
    r.headings.forEach(h => {
      const indent = '  '.repeat(h.level - 1);
      push(`${indent}- H${h.level}: ${h.text.slice(0, 100)}`);
    });
  }
  push('');
});

push('## 4. OLD-only pages (not on NEW)');
push('');
push('OLD pages without a NEW equivalent. These tie back to the SEO preservation list in `04-seo-keyword-mapping.md`. Heading structure shown here helps decide whether to migrate or 301.');
push('');
oldOnly.forEach(page => {
  const r = oldMap[page];
  push(`### \`${page}\``);
  push(`- OLD H1 count: ${r.h1Count}${r.violations.length > 0 ? ' · Violations: **' + r.violations.join(', ') + '**' : ''}`);
  push('');
  if (r.headings.length === 0) {
    push('_(no headings found)_');
  } else {
    push('Hierarchy:');
    r.headings.slice(0, 30).forEach(h => {
      const indent = '  '.repeat(h.level - 1);
      push(`${indent}- H${h.level}: ${h.text.slice(0, 100)}`);
    });
    if (r.headings.length > 30) push(`_(+${r.headings.length - 30} more)_`);
  }
  push('');
});

push('## 5. Summary counts');
push('');
push(`- NEW pages with no violations: **${Object.values(newMap).filter(r => r.violations.length === 0).length} / ${Object.keys(newMap).length}**`);
push(`- NEW pages with at least one violation: **${newViolations.length}**`);
push(`- OLD pages with no violations: **${Object.values(oldMap).filter(r => r.violations.length === 0).length} / ${Object.keys(oldMap).length}**`);
push(`- OLD pages with at least one violation: **${oldViolations.length}**`);
push('');
push('### Most common violation type on NEW');
const violationTypes = {};
newViolations.forEach(([_, r]) => {
  r.violations.forEach(v => {
    const t = v.split(' ')[0];
    violationTypes[t] = (violationTypes[t] || 0) + 1;
  });
});
Object.entries(violationTypes).sort((a, b) => b[1] - a[1]).forEach(([type, count]) => {
  push(`- ${type}: **${count}** page(s)`);
});

process.stdout.write(lines.join('\n'));
